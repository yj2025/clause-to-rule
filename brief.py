from pathlib import Path

from fpdf import FPDF

HERE = Path(__file__).parent
FONTS = HERE / "fonts"
OUT = HERE / "M2-2_브리핑_20260925.pdf"

INK = (28, 26, 23)
MUTED = (68, 64, 58)
FAINT = (106, 100, 92)
ACCENT = (122, 59, 29)
RULE = (216, 211, 203)
SUNK = (243, 241, 237)
OK = (47, 107, 63)
BAD = (156, 48, 37)

W = 210.0
M = 20.0
TW = W - 2 * M


class Brief(FPDF):
    def __init__(self):
        super().__init__(format="A4")
        self.set_auto_page_break(True, margin=22)
        self.add_font("nk", "", str(FONTS / "KR-Regular.ttf"))
        self.add_font("nk", "B", str(FONTS / "KR-Bold.ttf"))
        self.set_margins(M, 20, M)
        self.section = ""

    def footer(self):
        if self.page_no() == 1:
            return
        self.set_y(-16)
        self.set_font("nk", "", 7.5)
        self.set_text_color(*FAINT)
        self.cell(TW / 2, 5, self.section, align="L")
        self.cell(TW / 2, 5, str(self.page_no()), align="R")

    # ── 조판 ────────────────────────────────────────────────
    def h1(self, text, sub=None):
        self.ln(3)
        self.set_font("nk", "B", 17)
        self.set_text_color(*INK)
        self.multi_cell(TW, 8.4, text, new_x="LMARGIN")
        if sub:
            self.set_font("nk", "", 9.5)
            self.set_text_color(*MUTED)
            self.multi_cell(TW, 5.4, sub, new_x="LMARGIN")
        self.ln(1.5)
        y = self.get_y()
        self.set_draw_color(*ACCENT)
        self.set_line_width(0.7)
        self.line(M, y, M + 26, y)
        self.ln(4)
        self.section = text

    def h2(self, text):
        if self.get_y() > 232:
            self.add_page()
        self.ln(3.5)
        self.set_font("nk", "B", 11.5)
        self.set_text_color(*INK)
        self.multi_cell(TW, 6.2, text, new_x="LMARGIN")
        self.ln(1.2)

    def p(self, text, size=9.6, color=MUTED, gap=2.2):
        self.set_font("nk", "", size)
        self.set_text_color(*color)
        self.multi_cell(TW, 5.5, text, markdown=True, new_x="LMARGIN")
        self.ln(gap)

    def lead(self, text):
        self.set_font("nk", "", 10.4)
        self.set_text_color(*INK)
        self.multi_cell(TW, 6.0, text, markdown=True, new_x="LMARGIN")
        self.ln(3)

    def bullets(self, items, size=9.6):
        for it in items:
            self.set_x(M)
            self.set_font("nk", "B", size)
            self.set_text_color(*ACCENT)
            self.cell(5, 5.4, "·")
            self.set_font("nk", "", size)
            self.set_text_color(*MUTED)
            self.multi_cell(TW - 5, 5.4, it, markdown=True, new_x="LMARGIN")
        self.ln(2)

    def box(self, label, text, tone=ACCENT):
        pad = 4.0
        self.set_font("nk", "", 9.4)
        lines = self.multi_cell(TW - 2 * pad - 2, 5.3, text, dry_run=True,
                                output="LINES", markdown=True)
        h = len(lines) * 5.3 + 12
        if self.get_y() + h > 262:
            self.add_page()
        y0 = self.get_y()
        self.set_fill_color(*SUNK)
        self.rect(M, y0, TW, h, style="F")
        self.set_fill_color(*tone)
        self.rect(M, y0, 1.3, h, style="F")
        self.set_xy(M + pad, y0 + 3.2)
        self.set_font("nk", "B", 7.6)
        self.set_text_color(*tone)
        self.cell(TW - 2 * pad, 4, label)
        self.set_xy(M + pad, y0 + 8.0)
        self.set_font("nk", "", 9.4)
        self.set_text_color(*INK)
        self.multi_cell(TW - 2 * pad - 2, 5.3, text, markdown=True, new_x="LMARGIN")
        self.set_y(y0 + h + 3.5)

    def table(self, head, rows, widths, aligns=None, hi=None):
        aligns = aligns or ["L"] * len(head)
        hi = hi or set()
        need = 7 + len(rows) * 6.2
        if self.get_y() + need > 258:
            self.add_page()
        self.set_font("nk", "B", 7.8)
        self.set_text_color(*FAINT)
        for t, w, a in zip(head, widths, aligns):
            self.cell(w, 6, t, align=a)
        self.ln(6)
        self.set_draw_color(*RULE)
        self.set_line_width(0.3)
        self.line(M, self.get_y(), M + sum(widths), self.get_y())
        self.ln(1.2)
        for i, row in enumerate(rows):
            bold = i in hi
            for j, (t, w, a) in enumerate(zip(row, widths, aligns)):
                colour = INK if bold else MUTED
                if t.startswith("+") or t == "맞다":
                    colour = OK
                elif t.startswith("−") or t.startswith("-") and t[1:2].isdigit():
                    colour = BAD
                self.set_font("nk", "B" if bold or j == 0 else "", 9.0)
                self.set_text_color(*colour)
                self.cell(w, 6.2, t, align=a)
            self.ln(6.2)
            self.set_draw_color(238, 235, 230)
            self.line(M, self.get_y() - 0.6, M + sum(widths), self.get_y() - 0.6)
        self.ln(3)


