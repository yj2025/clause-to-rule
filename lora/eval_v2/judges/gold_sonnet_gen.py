def after_mat(cid, q1, q2, kind):
    note = (f"만기 후 해지 시 {kind} 기본금리의 1/2(1개월 이내)·1/4(1개월 초과) — 비율식이라 effect 가 없어 둘 다 UNSUPPORTED. "
            "구간은 날짜 비교로 서므로 조건은 남겼다(해지일 > 만기일; 1개월 경계는 만기일+1개월, 「이내」=이하, 「초과」=초과).")
    return note, [
        un(cid, 1, f"만기후 1개월 이내 해지 — 지급당시 해당기간별 {kind} 기본금리의 1/2: 비율식 없음", q1, {"and": [AFTER_MAT, WITHIN1M]}),
        un(cid, 2, f"만기후 1개월 초과 해지 — 지급당시 해당기간별 {kind} 기본금리의 1/4: 비율식 없음", q2, OVER1M),
    ]


