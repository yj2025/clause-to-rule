def var(n): return {"var": n}


MAT = {"==": [var("contract.termination_type"), "MATURITY"]}


def ok(cid, n, label, quote, cond, eff, let=None, guard=None):
    r = {"rule_id": f"{cid}-{n:02d}", "status": "OK", "label": label, "source": {"quote": quote}}
    if let: r["let"] = let
    if guard: r["guard"] = guard
    r["condition"] = cond
    r["effect"] = eff
    return r


def un(cid, n, label, quote, cond=None):
    return {"rule_id": f"{cid}-{n:02d}", "status": "UNSUPPORTED", "label": label,
            "source": {"quote": quote}, "condition": cond or {}}


def add(v): return {"type": "RATE_ADD", "value": v, "unit": "%p", "applies_to": "BASE_RATE"}
def ovr(v): return {"type": "RATE_OVERRIDE", "value": v, "unit": "%"}


DQ = {"type": "DISQUALIFY"}


def win(to_anchor, to_off, to_day, frm_off=0, frm_day="first", frm_anchor="contract.start_date"):
    return {"window": {"month_range": {
        "from": {"anchor": frm_anchor, "offset_months": frm_off, "day": frm_day},
        "to": {"anchor": to_anchor, "offset_months": to_off, "day": to_day}}}}


