def save(cid, note, rules):
    t = TRI[cid]
    assert t["verdict"] != "없음"
    json.dump({"clause_id": cid, "label": t["label"], "verdict": t["verdict"], "note": note, "rules": rules},
              open(OUT / f"{cid}.json", "w", encoding="utf8"), ensure_ascii=False, indent=2)


