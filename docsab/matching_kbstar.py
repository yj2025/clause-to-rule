def decisions():
    wb = openpyxl.load_workbook(XLSX, data_only=True, read_only=True)    # 서식이 깨져 read_only 로만 열린다
    rows = [r for r in wb["기획_배치결정표"].iter_rows(values_only=True) if any(v not in (None, "") for v in r)]
    hdr = rows[2]
    out = {}
    for r in rows[3:]:
        d = {k: ("" if v is None else str(v)) for k, v in zip(hdr, r)}
        name = "특수 규제·서비스 상태" if d["정보 항목"] == "서비스 상태" else d["정보 항목"]
        out[name] = {"decision": d["팀 최종 결정"], "prompt": d["프론트 제외한 내용 프롬프트 입력"],
                     "first": d["최초 출력 추천"], "mean": d["무엇을 뜻하는지"]}
    return out


